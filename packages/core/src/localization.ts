const messages: Record<AppLocale, Record<MessageKey, string>> = {
  en: englishMessages,
  'zh-CN': simplifiedChineseMessages,
};

export function resolveAppLocale(value?: string | null): AppLocale {
  return value?.toLocaleLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function translate(
  locale: AppLocale,
  key: MessageKey,
  variables: Record<string, string | number> = {},
): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(variables[name] ?? ''),
  );
}

export function translateDesignKind(locale: AppLocale, kind: 'concept' | 'variant') {
  return translate(locale, `design.kind.${kind}` as MessageKey);
}

export function translateGraphRelation(locale: AppLocale, type: string) {
  const key = `graph.relation.${type}` as MessageKey;
  return key in englishMessages
    ? translate(locale, key)
    : translate(locale, 'graph.relation.related_to');
}

export function translateDesignStatus(
  locale: AppLocale,
  status: 'exploring' | 'candidate' | 'review' | 'approved' | 'rejected' | 'archived',
) {
  return translate(locale, `design.status.${status}` as MessageKey);
}

export function translateNodeType(
  locale: AppLocale,
  nodeType:
    | 'text'
    | 'image'
    | 'reference'
    | 'sketch'
    | 'concept'
    | 'variant'
    | 'viewset'
    | 'cmf'
    | 'model3d'
    | 'group'
    | 'generation'
    | 'candidate',
) {
  if (nodeType === 'candidate') return translate(locale, 'generation.resultSelection');
  return translate(locale, `node.${nodeType}` as MessageKey);
}

