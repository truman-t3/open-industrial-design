export const supportedLocales = ['zh-CN', 'en'] as const;

export type AppLocale = (typeof supportedLocales)[number];

/** Presentation only: domain validation messages remain locale independent. */
export function translateGenerationConnectionError(locale: AppLocale, message: string): string {
  if (locale !== 'zh-CN') return message;
  const messages: Record<string, string> = {
    'Source and generation nodes must exist on the same board.': '素材与生成节点必须位于同一画板。',
    'Text-only generation cannot accept image connections. Choose an image task first.':
      '文生创意不接受图片连线，请先切换到图像任务。',
    'Only visual source nodes can be connected to generation.':
      '只能连接图片、草图、设计方案或候选结果。',
    'Generation connections cannot create a cycle.': '不能创建循环连接。',
    'This source is already connected.': '这份素材已经连接，无需重复连接。',
    'Only one main image can be connected.': '只能连接一张主图，请先移除已有主图。',
    'At most four additional references can be connected.': '最多连接四张补充参考图。',
  };
  return messages[message] ?? message;
}

